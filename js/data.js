function createProjects(records, category, options = {}) {
  return records.map(({ title, url, description, technologies = options.technologies ?? [], image = "", featured = false }, index) => {
    const hostname = new URL(url).hostname.replace(/^www\./, "");
    const slug = hostname.replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
    return {
      title,
      url,
      category,
      description,
      technologies: [...technologies],
      image,
      featured: featured || (options.featured?.includes(index) ?? false),
      recent: options.recent ?? false,
      slug,
      mark: title.trim().charAt(0).toUpperCase(),
      tags: [...new Set([category, ...technologies, ...(options.recent ? ["Recent"] : [])])]
    };
  });
}

